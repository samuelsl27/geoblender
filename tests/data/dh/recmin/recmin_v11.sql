-- Base RecMin sintética con el esquema 11, el de los volcados de RecMin que describe la
-- investigación 01 §6.1: tablas en mayúsculas, sin GRUPOS (ni SONDEOS.IDGRUPO) ni
-- FORMULAS, y ANGULOS.DISTANCIA en Single (bases antiguas). Datos inventados: ningún
-- dato de clientes (spec 005, T02). Mismo formato que recmin_v12.sql.
--
-- Lo que prueba: bocas en la superficie de tests/data/gis, un sondeo vertical (SV-1),
-- tablas adicionales de litología (LITOLOGIA2) y de muestras (MUESTRAS2), un elemento de
-- texto (Tex, unidad «txt», columna de texto), un análisis sin dato, valores en precisión
-- simple (0,1 y 4,35, también en DISTANCIA y en CL Z) y colores BGR asimétricos.

CREATE TABLE [SONDEOS] (
  [IDSONDEO] LONG CONSTRAINT [PK_SONDEOS] PRIMARY KEY,
  [SONDEO] TEXT(25) CONSTRAINT [UQ_SONDEOS_SONDEO] UNIQUE,
  [ESTE] DOUBLE,
  [NORTE] DOUBLE,
  [ELEVACION] DOUBLE,
  [IDSECTOR] SHORT,
  [PLAN] BIT,
  [PRIORIDAD] SHORT,
  [FECHA INI] DATETIME,
  [FECHA FIN] DATETIME,
  [CAT] SHORT,
  [CONTROL] BIT,
  [CL NORTE] SINGLE,
  [CL ESTE] SINGLE,
  [CL Z] SINGLE
);

CREATE TABLE [ANGULOS] (
  [ID] COUNTER CONSTRAINT [PK_ANGULOS] PRIMARY KEY,
  [IDSONDEO] LONG,
  [DISTANCIA] SINGLE,
  [INCLINACION] DOUBLE,
  [DIRECCION] DOUBLE
);

CREATE TABLE [LITOLOGIA] (
  [ID] COUNTER CONSTRAINT [PK_LITOLOGIA] PRIMARY KEY,
  [DESDE] SINGLE,
  [HASTA] SINGLE,
  [IDSONDEO] LONG,
  [IDLITO] LONG
);

CREATE TABLE [IDLITOLOGIA] (
  [IDLITO] LONG CONSTRAINT [PK_IDLITOLOGIA] PRIMARY KEY,
  [NOMBRE CORTO] TEXT(40),
  [COLOR] LONG,
  [ESTILO] SHORT,
  [DESCRIPCION] MEMO,
  [COLORPRINT] LONG,
  [ESTILOPRINT] SHORT,
  [VER] BIT,
  [DENSIDAD] SINGLE,
  [BMP] TEXT(255),
  [BMPprint] TEXT(255),
  [ORDEN] SHORT
);

CREATE TABLE [MUESTRAS] (
  [ID] COUNTER CONSTRAINT [PK_MUESTRAS] PRIMARY KEY,
  [DESDE] SINGLE,
  [HASTA] SINGLE,
  [IDSONDEO] LONG,
  [ELEMENTO 1] SINGLE,
  [ELEMENTO 2] SINGLE,
  [ELEMENTO 3] TEXT(50)
);

CREATE TABLE [ELEMENTOS] (
  [ELEMENTO] SHORT,
  [NOMBRE] TEXT(10),
  [UNIDAD] TEXT(10),
  [TABLA] BIT,
  [CALCULO] BIT,
  [ORDEN] SHORT,
  [DECIMALES] SHORT,
  [CONTADOR] COUNTER CONSTRAINT [PK_ELEMENTOS] PRIMARY KEY,
  [COLORES] TEXT(50)
);

CREATE TABLE [SECTORES] (
  [IDSECTOR] SHORT CONSTRAINT [PK_SECTORES] PRIMARY KEY,
  [SECTOR] TEXT(25),
  [DESCRIPCION] TEXT(255)
);

CREATE TABLE [ZONAS] (
  [IDZONA] LONG CONSTRAINT [PK_ZONAS] PRIMARY KEY,
  [ZONA] TEXT(25),
  [DESCRIPCION] TEXT(255),
  [DENSIDAD] SINGLE
);

CREATE TABLE [INTERSECCIONES] (
  [ID] COUNTER CONSTRAINT [PK_INTERSECCIONES] PRIMARY KEY,
  [DESDE] SINGLE,
  [HASTA] SINGLE,
  [ANGULO] SINGLE,
  [IDSONDEO] LONG,
  [IDZONA] LONG
);

CREATE TABLE [CORTES] (
  [ID] COUNTER CONSTRAINT [PK_CORTES] PRIMARY KEY,
  [IDZONA] LONG,
  [IDSONDEO] LONG,
  [DISTANCIA] DOUBLE,
  [AZIMUT] DOUBLE,
  [INCLINACION] DOUBLE
);

CREATE TABLE [ACTUALIZACION] (
  [ULTIMA] LONG
);

CREATE TABLE [GIROS] (
  [NOMBRE] TEXT(25),
  [OLDX] DOUBLE,
  [OLDY] DOUBLE,
  [OLDZ] DOUBLE,
  [NEWX] DOUBLE,
  [NEWY] DOUBLE,
  [NEWZ] DOUBLE,
  [GIROX] DOUBLE,
  [GIROY] DOUBLE,
  [GIROZ] DOUBLE,
  [USER] TEXT(4)
);

-- Tabla adicional de litología: la forma de LITOLOGIA con otro nombre.
CREATE TABLE [LITOLOGIA2] (
  [ID] COUNTER CONSTRAINT [PK_LITOLOGIA2] PRIMARY KEY,
  [DESDE] SINGLE,
  [HASTA] SINGLE,
  [IDSONDEO] LONG,
  [IDLITO] LONG
);

-- Tabla adicional de muestras: la forma de MUESTRAS con otro nombre.
CREATE TABLE [MUESTRAS2] (
  [ID] COUNTER CONSTRAINT [PK_MUESTRAS2] PRIMARY KEY,
  [DESDE] SINGLE,
  [HASTA] SINGLE,
  [IDSONDEO] LONG,
  [ELEMENTO 1] SINGLE,
  [ELEMENTO 2] SINGLE,
  [ELEMENTO 3] TEXT(50)
);

